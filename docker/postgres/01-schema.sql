-- Sweety schema for the Docker Postgres (mirrors the Supabase tables).
-- Runs automatically only when the postgres-data volume is created for the first time.

create table roles (
  id        bigint primary key,
  role_name text not null unique
);

insert into roles (id, role_name) values (1, 'patient'), (2, 'doctor');

create table users (
  id              bigint generated by default as identity primary key,
  full_name       text not null,
  email           text not null unique,
  password_hash   text not null,
  phone_number    text,
  date_of_birth   date,
  gender          text,
  blood_group     text,
  height_cm       numeric(5, 2),
  role_id         bigint references roles (id),
  assigned_doctor bigint references users (id),
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);

create table glucose_reading (
  id            bigint generated by default as identity primary key,
  user_id       bigint not null references users (id) on delete cascade,
  reading_date  date not null,
  time_slot     smallint not null check (time_slot between 0 and 3),
  glucose_value integer not null check (glucose_value between 40 and 600),
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  unique (user_id, reading_date, time_slot)
);

create table notifications (
  id           bigint generated by default as identity primary key,
  user_id      bigint not null references users (id) on delete cascade,
  reading_date date not null,
  time_slot    smallint not null check (time_slot between 0 and 3),
  kind         text not null check (kind in ('open', 'last_hour')),
  message      text not null,
  created_at   timestamptz not null default now(),
  unique (user_id, reading_date, time_slot, kind)
);

create index glucose_reading_user_date_idx on glucose_reading (user_id, reading_date);
create index users_assigned_doctor_idx on users (assigned_doctor);
